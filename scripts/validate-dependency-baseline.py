#!/usr/bin/env python3
"""Validate the reviewed Gradle dependency-verification baseline."""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NAMESPACE = "https://schema.gradle.org/dependency-verification"
NS = {"v": NAMESPACE}


def validate(path: Path, expected_sha256: str, expected_components: int, expected_artifacts: int) -> tuple[int, int]:
    raw = path.read_bytes()
    actual_sha256 = hashlib.sha256(raw).hexdigest()
    if actual_sha256 != expected_sha256:
        raise ValueError(f"SHA-256 mismatch: expected {expected_sha256}, got {actual_sha256}")

    root = ET.fromstring(raw)
    if root.tag != f"{{{NAMESPACE}}}verification-metadata":
        raise ValueError(f"Unexpected Gradle verification metadata root: {root.tag}")
    if root.findtext("v:configuration/v:verify-metadata", namespaces=NS) != "true":
        raise ValueError("Gradle checksum metadata verification must remain enabled")
    if root.findtext("v:configuration/v:verify-signatures", namespaces=NS) != "false":
        raise ValueError("Unexpected publisher-signature verification setting; preserve the reviewed configuration")

    components = root.findall("v:components/v:component", NS)
    component_coordinates: set[tuple[str, str, str]] = set()
    artifact_coordinates: list[tuple[str, str, str, str]] = []
    for component in components:
        group, name, version = (component.get(key, "") for key in ("group", "name", "version"))
        if not group or not name or not version:
            raise ValueError(f"Incomplete component coordinates: {component.attrib}")
        coordinate = (group, name, version)
        if coordinate in component_coordinates:
            raise ValueError(f"Duplicate component coordinates: {coordinate}")
        component_coordinates.add(coordinate)
        for artifact in component.findall("v:artifact", NS):
            artifact_name = artifact.get("name", "")
            if not artifact_name:
                raise ValueError(f"Missing artifact name for {coordinate}")
            checksums = artifact.findall("v:sha256", NS)
            if len(checksums) != 1:
                raise ValueError(f"Expected exactly one SHA-256 checksum: {coordinate} {artifact.attrib}")
            value = checksums[0].get("value", "")
            if not re.fullmatch(r"[0-9a-f]{64}", value):
                raise ValueError(f"Malformed SHA-256 value: {coordinate} {artifact.attrib}")
            if checksums[0].get("origin") != "Generated by Gradle":
                raise ValueError(f"Unexpected checksum origin: {coordinate} {artifact.attrib}")
            artifact_coordinates.append((*coordinate, artifact_name))

    if len(components) != expected_components or len(component_coordinates) != expected_components:
        raise ValueError(
            f"Unexpected component inventory: {len(components)} entries, "
            f"{len(component_coordinates)} unique; expected {expected_components}"
        )
    if len(artifact_coordinates) != expected_artifacts or len(set(artifact_coordinates)) != expected_artifacts:
        raise ValueError(
            f"Unexpected artifact inventory: {len(artifact_coordinates)} entries, "
            f"{len(set(artifact_coordinates))} unique; expected {expected_artifacts}"
        )
    return len(components), len(artifact_coordinates)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("metadata", type=Path)
    parser.add_argument("--expected-sha256", required=True)
    parser.add_argument("--expected-components", type=int, required=True)
    parser.add_argument("--expected-artifacts", type=int, required=True)
    args = parser.parse_args()
    try:
        components, artifacts = validate(args.metadata, args.expected_sha256, args.expected_components, args.expected_artifacts)
    except (OSError, ET.ParseError, ValueError) as exc:
        print(f"Dependency baseline validation failed: {exc}", file=sys.stderr)
        return 1
    print(
        "Reviewed dependency baseline validated: "
        f"{components} components, {artifacts} unique SHA-256 artifact entries, "
        f"SHA-256 {args.expected_sha256}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
